import { useState, useEffect } from 'react';
import { useParams, useNavigate, Link } from 'react-router-dom';
import { resolveInvite, redeemInvite, signInWithGoogle, getCurrentUser } from '@/lib/apiClient';
import { setPendingInviteCode, clearPendingInviteCode } from '@/lib/inviteStorage';
import { IdenticonAvatar } from '@/features/chat/components/IdenticonAvatar';
import type { ResolvedInvite, CurrentUser } from '@/types/api';
import { ArrowRight, AlertCircle, RefreshCw, MessageSquare } from 'lucide-react';

export default function InviteLandingPage() {
  const { code } = useParams<{ code: string }>();
  const navigate = useNavigate();

  const [loading, setLoading] = useState(true);
  const [currentUser, setCurrentUser] = useState<CurrentUser | null>(null);
  const [invite, setInvite] = useState<ResolvedInvite | null>(null);
  const [isInvalid, setIsInvalid] = useState(false);
  const [isSigningIn, setIsSigningIn] = useState(false);
  const [isRedeeming, setIsRedeeming] = useState(false);
  const [redeemError, setRedeemError] = useState<string | null>(null);

  useEffect(() => {
    if (!code) {
      setIsInvalid(true);
      setLoading(false);
      return;
    }

    let active = true;

    async function checkAuthAndResolve() {
      try {
        // 1. Check if visitor is signed in
        const userRes = await getCurrentUser().catch(() => ({ data: null, error: null }));
        if (active && userRes?.data) {
          setCurrentUser(userRes.data);
        }

        // 2. Resolve the invite code
        const res = await resolveInvite(code!);
        if (!active) return;

        if (res.error || !res.data) {
          clearPendingInviteCode();
          setIsInvalid(true);
        } else {
          setInvite(res.data);
        }
      } catch {
        if (active) {
          clearPendingInviteCode();
          setIsInvalid(true);
        }
      } finally {
        if (active) setLoading(false);
      }
    }

    checkAuthAndResolve();

    return () => {
      active = false;
    };
  }, [code]);

  const handleSignIn = async () => {
    if (!code) return;
    setIsSigningIn(true);
    // Store pending invite code in localStorage for post-login redemption
    setPendingInviteCode(code);
    try {
      await signInWithGoogle();
    } catch {
      setIsSigningIn(false);
    }
  };

  const handleConfirmStartChat = async () => {
    if (!code || isRedeeming) return;
    setIsRedeeming(true);
    setRedeemError(null);

    try {
      const res = await redeemInvite(code);
      clearPendingInviteCode();

      if (res.data) {
        // Navigate to new chat flow with inviter username pre-filled
        navigate(`/chats/new?username=${encodeURIComponent(res.data)}`);
      } else {
        setRedeemError(res.error?.message || 'Unable to start chat. The invite may have expired.');
      }
    } catch {
      setRedeemError('Network error while redeeming invite.');
    } finally {
      setIsRedeeming(false);
    }
  };

  if (loading) {
    return (
      <div className="min-h-screen w-full flex items-center justify-center bg-thread-bg text-thread-text p-4">
        <div className="flex flex-col items-center gap-3">
          <RefreshCw className="w-6 h-6 animate-spin text-thread-accent" />
          <p className="text-sm text-thread-muted">Checking invite link...</p>
        </div>
      </div>
    );
  }

  if (isInvalid || !invite) {
    return (
      <div className="min-h-screen w-full flex items-center justify-center bg-thread-bg text-thread-text p-4">
        <div className="max-w-md w-full bg-thread-surface border border-thread-border rounded-3xl p-6 sm:p-8 shadow-sm text-center space-y-5">
          <div className="w-14 h-14 rounded-full bg-red-100 dark:bg-red-950/50 text-red-600 dark:text-red-400 mx-auto flex items-center justify-center">
            <AlertCircle className="w-7 h-7" />
          </div>
          <div className="space-y-1.5">
            <h1 className="text-lg font-bold text-thread-text">
              This invite link isn't valid anymore
            </h1>
            <p className="text-sm text-thread-muted">
              The link may have expired, was regenerated by the owner, or is invalid.
            </p>
          </div>
          <div className="pt-2">
            <Link
              to="/signin"
              className="inline-flex items-center justify-center w-full py-3 px-4 rounded-xl bg-thread-accent text-white font-medium text-sm hover:bg-indigo-700 transition-colors focus:outline-none focus:ring-2 focus:ring-thread-accent min-h-[44px]"
            >
              Sign in to Thread
            </Link>
          </div>
        </div>
      </div>
    );
  }

  return (
    <div className="min-h-screen w-full flex items-center justify-center bg-thread-bg text-thread-text p-4">
      <div className="max-w-md w-full bg-thread-surface border border-thread-border rounded-3xl p-6 sm:p-8 shadow-sm text-center space-y-6">
        {/* Inviter Avatar & Header */}
        <div className="space-y-3">
          <div className="flex justify-center">
            <IdenticonAvatar
              seed={invite.avatarSeed || invite.username}
              label={invite.displayName || invite.username}
              size={72}
            />
          </div>
          <div className="space-y-1">
            <h1 className="text-xl font-bold text-thread-text">
              {invite.displayName || `@${invite.username}`}
            </h1>
            <p className="text-sm text-thread-text font-medium">
              <span className="font-mono text-thread-muted">@{invite.username}</span> invited you to Thread
            </p>
          </div>
          <p className="text-xs text-thread-muted max-w-xs mx-auto">
            Thread is a clean, free text-only messenger designed for fast, focused conversations.
          </p>
        </div>

        {redeemError && (
          <div className="p-3 rounded-xl bg-red-50 dark:bg-red-950/40 border border-red-200 dark:border-red-900/50 text-red-700 dark:text-red-300 text-xs flex items-center gap-2 text-left">
            <AlertCircle className="w-4 h-4 shrink-0" />
            <span>{redeemError}</span>
          </div>
        )}

        {/* Action button based on state */}
        <div className="pt-2">
          {currentUser && currentUser.usernameSet ? (
            <div className="space-y-3">
              <p className="text-xs text-thread-muted">
                Start a chat with <strong className="text-thread-text">@{invite.username}</strong>?
              </p>
              <button
                type="button"
                onClick={handleConfirmStartChat}
                disabled={isRedeeming}
                className="w-full py-3 px-4 rounded-xl bg-thread-accent text-white font-medium text-sm flex items-center justify-center gap-2 hover:bg-indigo-700 transition-colors focus:outline-none focus:ring-2 focus:ring-thread-accent min-h-[44px]"
              >
                {isRedeeming ? (
                  <>
                    <RefreshCw className="w-4 h-4 animate-spin" />
                    <span>Connecting...</span>
                  </>
                ) : (
                  <>
                    <MessageSquare className="w-4 h-4" />
                    <span>Start chat with @{invite.username}</span>
                  </>
                )}
              </button>
            </div>
          ) : (
            <button
              type="button"
              onClick={handleSignIn}
              disabled={isSigningIn}
              className="w-full py-3 px-4 rounded-xl bg-thread-accent text-white font-medium text-sm flex items-center justify-center gap-2 hover:bg-indigo-700 transition-colors focus:outline-none focus:ring-2 focus:ring-thread-accent min-h-[44px]"
            >
              {isSigningIn ? (
                <>
                  <RefreshCw className="w-4 h-4 animate-spin" />
                  <span>Signing in...</span>
                </>
              ) : (
                <>
                  <span>Sign in with Google to chat</span>
                  <ArrowRight className="w-4 h-4" />
                </>
              )}
            </button>
          )}
        </div>
      </div>
    </div>
  );
}
